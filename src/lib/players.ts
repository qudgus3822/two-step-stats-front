// [신설: 2026-09-04 10:40, 김병현 작성] "이 이름이 진짜 회원인가?"를 판단하는 곳.
//
// 기록지에는 회원이 아닌 사람의 기록도 '게스트'라는 이름 하나로 뭉쳐서 들어온다.
// 그래서 '게스트' 행은 한 사람의 기록이 아니라 "여러 손님의 기록 덩어리"다 —
// 기준 선수로 고르면 서로 다른 사람들을 한 사람인 척 합쳐 보게 되니 의미가 없다.
//
// 규칙을 여기 한 곳에만 둔다. 나중에 손님이 늘어 '게스트1', '게스트2' 처럼 숫자 접미사가
// 붙어도(동명이인 표기 관례와 같은 방식) 그대로 걸리도록 숫자까지 함께 본다.
// 반대로 '게스트김' 같이 뒤에 다른 글자가 붙은 진짜 이름은 걸리지 않는다.
const GUEST_NAME = /^게스트\d*$/;

/** 회원이 아닌 '게스트' 이름이면 true. */
export function isGuestPlayer(name: string): boolean {
  return GUEST_NAME.test(name.trim());
}
